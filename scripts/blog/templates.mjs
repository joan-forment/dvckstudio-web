// Cover inside a card. The title link already names the card, so the image
// is decorative here (empty alt); it has its own alt in the post hero.
const cardMedia = (post, className, sizes) =>
  post.cover
    ? `<div class="${className}"><img src="${post.cover.small || post.cover.src}"${
        post.cover.small ? ` srcset="${post.cover.small} 800w, ${post.cover.src} 1600w" sizes="${sizes}"` : ""
      } alt="" width="1600" height="900" loading="lazy" decoding="async" /></div>`
    : "";

const chip = (category) => `<span class="blog-chip">${esc(category.name)}</span>`;

// Reading time as a pill with one dot per minute (capped), so "how long is
// this" is readable at a glance instead of buried in a meta line.
const timePill = (minutes) =>
  `<span class="blog-time"><span class="blog-time-dots" aria-hidden="true">${"<i></i>".repeat(Math.min(minutes, 10))}</span>${minutes} min</span>`;

const draftBadge = (post) => (post.isDraft ? `<span class="blog-draft">Borrador</span>` : "");

// Short date for cards: "24 sept 2026".
const shortDate = (iso) =>
  new Intl.DateTimeFormat("es-ES", { day: "numeric", month: "short", year: "numeric", timeZone: "UTC" })
    .format(new Date(`${iso}T00:00:00Z`))
    .replace(".", "");

