function categoryNav(posts, activeSlug) {
  const link = (href, label, count, active) =>
    `<li><a class="blog-filter" href="${href}"${active ? ' aria-current="page"' : ""}>${esc(label)} <span>${count}</span></a></li>`;
  const items = CATEGORIES.map((c) => ({ c, count: posts.filter((p) => p.category.slug === c.slug).length }))
    .filter(({ count }) => count > 0)
    .map(({ c, count }) => link(`/blog/categoria/${c.slug}`, c.name, count, c.slug === activeSlug));
  return `
        <nav class="blog-filters" aria-label="Categorías del blog">
          <ul>
            ${link("/blog", "Todo", posts.length, !activeSlug)}
            ${items.join("\n            ")}
          </ul>
        </nav>`;
}

function pagination(basePath, page, pageCount) {
  if (pageCount < 2) return "";
  const href = (n) => (n === 1 ? basePath : `${basePath}/pagina/${n}`);
  const pages = Array.from({ length: pageCount }, (_, i) => i + 1)
    .map((n) =>
      n === page
        ? `<li><span class="blog-page" aria-current="page">${n}</span></li>`
        : `<li><a class="blog-page" href="${href(n)}">${n}</a></li>`,
    )
    .join("");
  const prev = page > 1 ? `<a class="blog-page blog-page--step" href="${href(page - 1)}" rel="prev">← Anteriores</a>` : "";
  const next = page < pageCount ? `<a class="blog-page blog-page--step" href="${href(page + 1)}" rel="next">Siguientes →</a>` : "";
  return `
      <nav class="blog-pagination container" aria-label="Páginas del blog">
        ${prev}
        <ol>${pages}</ol>
        ${next}
      </nav>`;
}

