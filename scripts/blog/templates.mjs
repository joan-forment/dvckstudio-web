export function renderRss(posts) {
  const items = posts
    .slice(0, 30)
    .map(
      (p) => `
    <item>
      <title>${esc(p.title)}</title>
      <link>${SITE}${p.url}</link>
      <guid isPermaLink="true">${SITE}${p.url}</guid>
      <description>${esc(p.description)}</description>
      <category>${esc(p.category.name)}</category>
      <pubDate>${new Date(`${p.date}T08:00:00Z`).toUTCString()}</pubDate>
    </item>`,
    )
    .join("");
  const lastBuild = posts[0] ? new Date(`${posts[0].date}T08:00:00Z`).toUTCString() : new Date().toUTCString();
  return `<?xml version="1.0" encoding="UTF-8"?>
<rss version="2.0" xmlns:atom="http://www.w3.org/2005/Atom">
  <channel>
    <title>Blog de DvckStudio</title>
    <link>${SITE}/blog</link>
    <atom:link href="${SITE}/blog/rss.xml" rel="self" type="application/rss+xml" />
    <description>Guías prácticas de inteligencia artificial, desarrollo web, diseño y SEO del equipo de DvckStudio.</description>
    <language>es-ES</language>
    <lastBuildDate>${lastBuild}</lastBuildDate>${items}
  </channel>
</rss>
`;
}
