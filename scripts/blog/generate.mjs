// Writes the blog as real HTML files (blog.html + blog/**) so Vite bundles
// them like any hand-written page, and keeps public/sitemap.xml in sync.
import fs from "fs";
import path from "path";
import { CATEGORIES, ROOT, SITE, loadPosts, localToday } from "./content.mjs";
import { PAGE_SIZE, renderListing, renderPost, renderRss } from "./templates.mjs";

export const OUT_DIR = path.join(ROOT, "blog");
const SITEMAP = path.join(ROOT, "public/sitemap.xml");
const SITEMAP_START = "<!-- blog:start (generated by scripts/blog, do not edit) -->";
const SITEMAP_END = "<!-- blog:end -->";

function write(relPath, html, pages) {
  const file = path.join(ROOT, relPath);
  fs.mkdirSync(path.dirname(file), { recursive: true });
  fs.writeFileSync(file, html);
  pages.push(relPath.replace(/\\/g, "/"));
}

// Related posts: same category first, then shared tags, newest wins ties.
function relatedTo(post, posts) {
  return posts
    .filter((p) => p.slug !== post.slug)
    .map((p) => ({
      p,
      score: (p.category.slug === post.category.slug ? 2 : 0) + p.tags.filter((t) => post.tags.includes(t)).length,
    }))
    .sort((a, b) => b.score - a.score || b.p.date.localeCompare(a.p.date))
    .slice(0, 3)
    .map(({ p }) => p);
}

function writeListing({ allPosts, posts, category, pages }) {
  const basePath = category ? `blog/categoria/${category.slug}` : "blog";
  // The blog home has a featured card, so its first page holds one extra post.
  const firstPageSize = category ? PAGE_SIZE : PAGE_SIZE + 1;
  const pageCount = Math.max(1, 1 + Math.ceil(Math.max(0, posts.length - firstPageSize) / PAGE_SIZE));

  for (let page = 1; page <= pageCount; page++) {
    const start = page === 1 ? 0 : firstPageSize + (page - 2) * PAGE_SIZE;
    const end = page === 1 ? firstPageSize : start + PAGE_SIZE;
    const urlPath = page === 1 ? `/${basePath}` : `/${basePath}/pagina/${page}`;
    const html = renderListing({ allPosts, posts: posts.slice(start, end), category, page, pageCount, path: urlPath });
    write(`${urlPath.slice(1)}.html`, html, pages);
  }
}

function updateSitemap(posts) {
  const latest = posts[0]?.date || localToday();
  const entry = (loc, lastmod, changefreq, priority) =>
    `  <url>\n    <loc>${SITE}${loc}</loc>\n    <lastmod>${lastmod}</lastmod>\n    <changefreq>${changefreq}</changefreq>\n    <priority>${priority}</priority>\n  </url>`;

  const urls = [entry("/blog", latest, "daily", "0.8")];
  for (const c of CATEGORIES) {
    const inCategory = posts.filter((p) => p.category.slug === c.slug);
    // Same threshold as the noindex rule in templates.mjs.
    if (inCategory.length >= 3) urls.push(entry(`/blog/categoria/${c.slug}`, inCategory[0].date, "weekly", "0.5"));
  }
  for (const p of posts) urls.push(entry(p.url, p.updated || p.date, "monthly", "0.7"));

  const block = `${SITEMAP_START}\n${urls.join("\n")}\n  ${SITEMAP_END}`;
  const xml = fs.readFileSync(SITEMAP, "utf8");
  const pattern = new RegExp(`${SITEMAP_START.replace(/[.*+?^${}()|[\]\\]/g, "\\$&")}[\\s\\S]*?${SITEMAP_END}`);
  const next = pattern.test(xml) ? xml.replace(pattern, block) : xml.replace("</urlset>", `  ${block}\n</urlset>`);
  if (next !== xml) fs.writeFileSync(SITEMAP, next);
}

// Returns the generated HTML paths (relative to the project root) and the RSS.
export function generateBlog({ includeDrafts = false } = {}) {
  const posts = loadPosts({ includeDrafts });
  const published = posts.filter((p) => !p.isDraft);
  const pages = [];

  // blog/ only ever holds generated files, so it is safe to rebuild it whole.
  fs.rmSync(OUT_DIR, { recursive: true, force: true });

  writeListing({ allPosts: posts, posts, category: null, pages });
  for (const category of CATEGORIES) {
    const inCategory = posts.filter((p) => p.category.slug === category.slug);
    if (inCategory.length) writeListing({ allPosts: posts, posts: inCategory, category, pages });
  }

  posts.forEach((post, i) => {
    const html = renderPost(post, { related: relatedTo(post, posts), newer: posts[i - 1], older: posts[i + 1] });
    write(`blog/${post.slug}.html`, html, pages);
  });

  // Drafts never reach the sitemap or the feed, even in dev.
  updateSitemap(published);

  const warnings = posts.flatMap((p) => p.warnings.map((w) => `${p.slug}: ${w}`));
  return { pages, rss: renderRss(published), posts, warnings };
}
